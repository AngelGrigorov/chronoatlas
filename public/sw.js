// Offline: every file of the atlas that has been loaded once is kept, and with no network
// the kept copy is used. Network first, so a new version is always picked up when online.
const CACHE = 'chronoatlas';

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(self.clients.claim()));

self.addEventListener('fetch', e => {
  const req = e.request;
  // Only the atlas's own files; Wikipedia stays live.
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    fetch(req)
      .then(res => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then(c => c.put(req, copy));
        }
        return res;
      })
      .catch(() => caches.match(req).then(r => r || Response.error())),
  );
});
